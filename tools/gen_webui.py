#!/usr/bin/env python3
"""Embed the web UI (and an optional icon) as a C header.

Usage: gen_webui.py <index.html> <out.h> [icon.png]

The generated file is not checked in; the Makefile rebuilds it whenever the
HTML or the icon changes.
"""

import pathlib
import sys


def emit_array(fh, name, data, ctype="unsigned char"):
    fh.write(f"static const {ctype} {name}[] = {{\n")
    line = []
    for i, byte in enumerate(data):
        line.append(f"0x{byte:02x},")
        if len(line) == 16:
            fh.write("    " + " ".join(line) + "\n")
            line = []
    if line:
        fh.write("    " + " ".join(line) + "\n")
    if not data:
        fh.write("    0x00,\n")
    fh.write("};\n")


def emit_len(fh, name, value):
    fh.write(f"static const unsigned long {name} = {value}ul;\n")


def main(argv):
    if len(argv) < 3:
        print("usage: gen_webui.py <index.html> <out.h> [icon.png]", file=sys.stderr)
        return 2

    html = pathlib.Path(argv[1]).read_bytes()
    icon = b""
    if len(argv) > 3:
        icon_path = pathlib.Path(argv[3])
        if icon_path.is_file():
            icon = icon_path.read_bytes()
        else:
            print(f"gen_webui.py: {icon_path} not found, skipping icon", file=sys.stderr)

    out = pathlib.Path(argv[2])
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", encoding="ascii", newline="\n") as fh:
        fh.write("/* Generated by tools/gen_webui.py - do not edit. */\n")
        fh.write("#ifndef PS5B_WEBUI_ASSETS_H\n#define PS5B_WEBUI_ASSETS_H\n\n")
        emit_array(fh, "k_webui_html", html)
        emit_len(fh, "k_webui_html_len", len(html))
        fh.write("\n")
        emit_array(fh, "k_webui_icon", icon)
        emit_len(fh, "k_webui_icon_len", len(icon))
        fh.write("\n#endif /* PS5B_WEBUI_ASSETS_H */\n")

    print(f"gen_webui.py: html={len(html)} B icon={len(icon)} B -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
